import assert from 'node:assert/strict';
import { MinecraftOutageWatch } from './dist/services/minecraftWatch.js';
const watch = new MinecraftOutageWatch();
const now = Date.now();
const longAgo = new Date(now - 300_000).toISOString();
assert.equal(watch.observe('active', false, longAgo, now), null);
assert.equal(watch.observe('active', true, longAgo, now), null, 'a healthy ping resets transient failures');
assert.equal(watch.observe('active', false, longAgo, now), null);
assert.equal(watch.observe('active', false, longAgo, now), null);
assert.match(watch.observe('active', false, longAgo, now), /outage reported/);
assert.equal(watch.observe('active', false, longAgo, now), null, 'a sustained outage is reported once to avoid recovery loops');
assert.equal(watch.observe('active', true, longAgo, now), null);
assert.equal(watch.observe('failed', false, longAgo, now), null);
assert.match(watch.observe('failed', false, longAgo, now), /service state is failed/);
const startup = new MinecraftOutageWatch();
for (let i = 0; i < 5; i++) assert.equal(startup.observe('active', false, new Date(now).toISOString(), now + i * 15_000), null, 'allow startup grace');
for (let i = 0; i < 5; i++) assert.equal(startup.observe('deactivating', false, longAgo, now), null, 'do not interrupt a service transition');
for (let i = 0; i < 5; i++) assert.equal(startup.observe(null, false, null, now), null, 'unknown service state does not justify a recovery');
console.log('Minecraft outage watch: transient failures, outage detection, startup grace, transitions and duplicate suppression passed');
